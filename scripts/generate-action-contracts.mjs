import {readFileSync, writeFileSync} from 'node:fs';
const source = new URL('../backend/app/llm/action_contracts.json', import.meta.url);
const target = new URL('../src/app/core/services/assistant/action-contracts.generated.ts', import.meta.url);
const contracts = JSON.parse(readFileSync(source, 'utf8'));
const result = '// Generated by scripts/generate-action-contracts.mjs; edit backend/app/llm/action_contracts.json.\n'
  + 'export const ACTION_CONTRACTS: Record<string, {parameters: string[]; minArgs: number; normalize?: string; example: unknown[]}> = '
  + JSON.stringify(contracts, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== result) throw new Error('Action contracts are stale; run node scripts/generate-action-contracts.mjs');
} else writeFileSync(target, result);
